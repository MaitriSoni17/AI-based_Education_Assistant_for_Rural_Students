import * as XLSX from 'xlsx';
import { jsPDF } from 'jspdf';
import { FirestoreUser, FirestoreCertificate } from './firebase';

export interface VillageHubItem {
  name: string;
  count: number;
  pct: string;
  totalXP: number;
}

export interface CurriculumFolderItem {
  id: string;
  name: string;
  parentId: string | null;
  createdAt: string;
}

export interface CurriculumFileItem {
  id: string;
  name: string;
  subject: string;
  category: string;
  materialType?: string;
  size: string;
  uploadedAt: string;
  folderId?: string;
  externalUrl?: string;
}

export interface ExportDataPayload {
  adminUser: { name: string; mobile: string; role: string };
  usersList: FirestoreUser[];
  villageHubStats: VillageHubItem[];
  certificates: FirestoreCertificate[];
  curriculumFolders: CurriculumFolderItem[];
  curriculumFiles: CurriculumFileItem[];
  totalStudyMinsAll: number;
  totalPointsAll: number;
  dateFilterLabel?: string;
}

// Helper to trigger browser file download
export function triggerFileDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

