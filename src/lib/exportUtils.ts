  const timestamp = new Date().toISOString().split('T')[0];
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  // Document Styling Constants
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  let y = margin;

  // Header Banner
  doc.setFillColor(30, 41, 59); // Slate-800
  doc.rect(0, 0, pageWidth, 28, 'F');

  doc.setFillColor(224, 122, 95); // Coral Accent
  doc.rect(0, 28, pageWidth, 2, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('GYAANBOT RURAL EDUCATION PLATFORM', margin, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225);
  doc.text(`Official Executive Analytics & Performance Report | Generated: ${new Date().toLocaleString()}`, margin, 20);

  y = 38;

  // Admin Meta Info Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, y, pageWidth - margin * 2, 20, 2, 2, 'FD');

  doc.setTextColor(51, 65, 85);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('REPORT METADATA', margin + 4, y + 5);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text(`Generated By: ${payload.adminUser.name} (${payload.adminUser.mobile}) | Role: ${payload.adminUser.role.toUpperCase()}`, margin + 4, y + 10);
  doc.text(`Analytics Period: ${payload.dateFilterLabel || 'Full Analytics (All Time)'}`, margin + 4, y + 15);

  y += 26;

  // Executive KPI Summary Section Title
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('1. Key Performance Metrics Overview', margin, y);
  y += 6;

  // KPI Grid Cards (2x2)
  const cardW = (pageWidth - margin * 2 - 6) / 2;
  const cardH = 16;

  const kpis = [
    { label: 'Total Active Students', val: `${payload.usersList.filter((u) => u.role === 'student').length}` },
    { label: 'Total Village Hubs', val: `${payload.villageHubStats.length}` },
    { label: 'Total Study Hours Logged', val: `${Number((payload.totalStudyMinsAll / 60).toFixed(1))} Hours` },
    { label: 'Certificates Issued', val: `${payload.certificates.length}` },
  ];

  kpis.forEach((kpi, idx) => {
    const col = idx % 2;
    const row = Math.floor(idx / 2);
    const cx = margin + col * (cardW + 6);
    const cy = y + row * (cardH + 4);

    doc.setFillColor(255, 255, 255);
    doc.setDrawColor(203, 213, 225);
    doc.roundedRect(cx, cy, cardW, cardH, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(kpi.label.toUpperCase(), cx + 4, cy + 5);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(15, 23, 42);
    doc.text(kpi.val, cx + 4, cy + 12);
  });

  y += cardH * 2 + 12;

  // Section 2: Rural Village Hub Activity
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('2. Regional Village Hub Performance', margin, y);
  y += 6;

  // Table Header
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageWidth - margin * 2, 7, 'F');
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(51, 65, 85);
  doc.text('VILLAGE HUB / SCHOOL NAME', margin + 3, y + 5);
  doc.text('ENROLLED STUDENTS', margin + 95, y + 5);
  doc.text('ENGAGEMENT %', margin + 140, y + 5);

  y += 7;

  payload.villageHubStats.slice(0, 8).forEach((hub) => {
    if (y > pageHeight - 20) {
      doc.addPage();
      y = margin;
    }
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(30, 41, 59);
    doc.text(hub.name.substring(0, 45), margin + 3, y + 4);
    doc.text(`${hub.count} students`, margin + 95, y + 4);
    doc.text(hub.pct, margin + 140, y + 4);

    doc.setDrawColor(241, 245, 249);
    doc.line(margin, y + 6, pageWidth - margin, y + 6);
    y += 7;
  });

  y += 6;

  // Section 3: Issued Certificates Highlights
  if (y > pageHeight - 40) {
    doc.addPage();
    y = margin;
  }

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('3. Issued Course Certificates Summary', margin, y);
  y += 6;

  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageWidth - margin * 2, 7, 'F');
