/**
 * Export Master Multi-Sheet Excel Workbook (.xlsx)
 */
export function exportMasterAnalyticsExcel(payload: ExportDataPayload) {
  const timestamp = new Date().toISOString().split('T')[0];
  const wb = XLSX.utils.book_new();

  // Sheet 1: Executive Overview KPIs
  const summaryRows = [
    { Metric: 'Report Name', Value: 'GyaanBot Primary Education Platform Analytics' },
    { Metric: 'Generated Date', Value: new Date().toLocaleString() },
    { Metric: 'Generated By', Value: `${payload.adminUser.name} (${payload.adminUser.mobile})` },
    { Metric: 'Filtered Period / Date Range', Value: payload.dateFilterLabel || 'Full Analytics (All Time)' },
    { Metric: 'Total Active Students', Value: payload.usersList.filter((u) => u.role === 'student').length },
    { Metric: 'Total Teachers', Value: payload.usersList.filter((u) => u.role === 'teacher').length },
    { Metric: 'Total Administrators', Value: payload.usersList.filter((u) => u.role === 'admin').length },
    { Metric: 'Total Study Hours Logged', Value: Number((payload.totalStudyMinsAll / 60).toFixed(1)) },
    { Metric: 'Total Accumulated Student XP', Value: payload.totalPointsAll },
    { Metric: 'Total Village Hubs Tracked', Value: payload.villageHubStats.length },
    { Metric: 'Total Certificates Issued', Value: payload.certificates.length },
    { Metric: 'Curriculum Resources Library Files', Value: payload.curriculumFiles.length },
  ];
  const wsSummary = XLSX.utils.json_to_sheet(summaryRows);
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Executive Summary');

  // Sheet 2: Student & User Directory
  const userRows = payload.usersList.map((u, idx) => ({
    'S.No': idx + 1,
    'User ID / UID': (u as any).uid || u.mobile || 'N/A',
    'Full Name': u.name || 'Anonymous',
    'Mobile Number': u.mobile || '',
    'Role': (u.role || 'student').toUpperCase(),
    'Village Hub / School': u.village || u.school || 'Unspecified',
    'Grade / Class': (u as any).grade || u.standard || 'N/A',
    'Streak (Days)': u.streakDays || 0,
    'XP Points': u.totalPoints || 0,
    'Study Minutes': u.studyMins || 0,
    'Joined Date': (u as any).createdAt ? new Date((u as any).createdAt).toLocaleDateString() : (u.signupDate || 'N/A'),
  }));
  const wsUsers = XLSX.utils.json_to_sheet(userRows.length > 0 ? userRows : [{ Note: 'No user records' }]);
  XLSX.utils.book_append_sheet(wb, wsUsers, 'Student Directory');

  // Sheet 3: Village Hub Activity
  const hubRows = payload.villageHubStats.map((h, idx) => ({
    'S.No': idx + 1,
    'Village Hub / School Name': h.name,
    'Enrolled Students': h.count,
    'Active Engagement Rate': h.pct,
    'Total Accumulated XP': h.totalXP,
  }));
  const wsHubs = XLSX.utils.json_to_sheet(hubRows.length > 0 ? hubRows : [{ Note: 'No hub records' }]);
  XLSX.utils.book_append_sheet(wb, wsHubs, 'Village Hubs');

  // Sheet 4: Certificates Ledger
  const certRows = payload.certificates.map((c, idx) => ({
    'S.No': idx + 1,
    'Certificate ID': c.id,
    'Student Name': c.studentName,
    'Student Mobile': c.studentMobile,
    'Course / Module Title': c.title,
    'Score (%)': c.score || 100,
    'Issue Date': c.date,
    'Verification Status': c.status.toUpperCase(),
  }));
  const wsCerts = XLSX.utils.json_to_sheet(certRows.length > 0 ? certRows : [{ Note: 'No certificate records' }]);
  XLSX.utils.book_append_sheet(wb, wsCerts, 'Certificates Ledger');

  // Sheet 5: Curriculum Inventory
  const currRows = payload.curriculumFiles.map((f, idx) => ({
    'S.No': idx + 1,
    'File Name': f.name,
    'Material Type': f.materialType ? (f.materialType === 'notes' ? 'Notes & Summaries' : f.materialType === 'ebook' ? 'E-Books & Textbooks' : f.materialType === 'pyq' ? 'Previous Year Paper' : f.materialType === 'practice_questions' ? 'Practice Questions' : f.materialType) : 'Notes',
    'Subject': f.subject,
    'Category / Format': f.category,
    'File Size': f.size,
    'Upload Date': f.uploadedAt,
    'External Resource Link': f.externalUrl || 'N/A',
  }));
  const wsCurr = XLSX.utils.json_to_sheet(currRows.length > 0 ? currRows : [{ Note: 'No curriculum files' }]);
  XLSX.utils.book_append_sheet(wb, wsCurr, 'Curriculum Library');

  // Write and download .xlsx
  const excelBuffer = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
  const blob = new Blob([excelBuffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  triggerFileDownload(blob, `GyaanBot_Master_Analytics_Report_${timestamp}.xlsx`);
}

/**
 * Single Category Excel Export
 */
export function exportCategoryExcel(categoryName: string, headers: string[], rows: (string | number)[][], filenamePrefix: string) {
  const timestamp = new Date().toISOString().split('T')[0];
  const wb = XLSX.utils.book_new();

  const data = [headers, ...rows];
  const ws = XLSX.utils.aoa_to_sheet(data);
  XLSX.utils.book_append_sheet(wb, ws, categoryName.substring(0, 30));

  const excelBuffer = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
  const blob = new Blob([excelBuffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  triggerFileDownload(blob, `${filenamePrefix}_${timestamp}.xlsx`);
}

